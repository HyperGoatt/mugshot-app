#!/usr/bin/env python3
"""Generate Mugsy's typed Swift catalog and verify the immutable identity rig.

PNG validation uses only the standard library. Optical identity review is a
separate recorded gate: file hashes and alpha do not establish character likeness.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import struct
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "docs/brand/identity/mugsy-spec.json"
SWIFT = ROOT / "testMugshot/Design/MugsyPoseCatalog.swift"
ASSETS = ROOT / "testMugshot/Assets.xcassets"


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def swift_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def render(spec: dict) -> str:
    poses = spec["poses"]
    cases = "\n".join("    case " + pose["native_case"] for pose in poses)
    names = "\n".join(f"        case .{p['native_case']}: return {swift_string(p['asset_name'])}" for p in poses)
    titles = "\n".join(f"        case .{p['native_case']}: return {swift_string(p['title'])}" for p in poses)
    ids = "\n".join(f"        case .{p['native_case']}: return {swift_string(p['id'])}" for p in poses)
    configurations = []
    bounds = []
    for pose in poses:
        coordinates = pose.get("artwork_bounds", [0, 0, 1, 1])
        bounds.append(f"        case .{pose['native_case']}: return CGRect(x: {coordinates[0]}, y: {coordinates[1]}, width: {coordinates[2]}, height: {coordinates[3]})")
        liquid = ".empty"
        if pose["id"] == "cozy":
            liquid = ".coffee(fillProgress: 0.74, steamIntensity: 0.4)"
        elif pose["id"] == "pause":
            liquid = ".coffee(fillProgress: 0.45)"
        leg = ".init(bendProgress: 0.42, weightShift: 0.2)" if pose["id"] == "celebrate" else ".neutral"
        configurations.append(f"""        case .{pose['native_case']}:
            return .init(
                expression: .{pose['expression']},
                prop: .{pose['prop']},
                outfit: .{pose['outfit']},
                armPose: .{pose['arm_pose']},
                pose: .{pose['pose']},
                legArticulation: {leg},
                liquid: {liquid}
            )""")
    configuration_source = "\n".join(configurations)
    bounds_source = "\n".join(bounds)
    return f"""// Generated by scripts/mugsy-catalog.py from the single pose specification.
// Do not hand-edit. Identity geometry remains in MugsyModelView.
import SwiftUI

enum MugsyCatalogPose: String, CaseIterable, Identifiable {{
{cases}

    static let identityMasterAsset = {swift_string(spec['native_master'])}
    static let identityReferenceSHA256 = {swift_string(spec['reference_sha256'])}

    var id: String {{ rawValue }}

    var specificationID: String {{
        switch self {{
{ids}
        }}
    }}

    var assetName: String {{
        switch self {{
{names}
        }}
    }}

    var title: String {{
        switch self {{
{titles}
        }}
    }}

    var configuration: MugsyModelConfiguration {{
        switch self {{
{configuration_source}
        }}
    }}

    /// Alpha-derived display registration. The PNG itself is never cropped.
    var artworkBounds: CGRect {{
        switch self {{
{bounds_source}
        }}
    }}
}}
"""


def source_block(source: str, marker: str) -> bytes:
    start = source.index(marker)
    brace = source.index("{", start)
    depth, end = 1, brace + 1
    while depth:
        depth += (source[end] == "{") - (source[end] == "}")
        end += 1
    return source[start:end].encode()


def verify_native_previews(spec: dict) -> None:
    folder = ROOT / "docs/brand/native-renders"
    manifest = json.loads((folder / "manifest.json").read_text())
    expected_sources = {
        "testMugshot/Design/BrandColors.swift",
        "testMugshot/Design/MugsyDesignSystem.swift",
        "testMugshot/Design/MugsyPoseCatalog.swift",
        "testMugshot/Views/Components/MugsyModelView.swift",
        "testMugshot/Views/Components/MugsyExpandedAccessoryView.swift",
    }
    if set(manifest["source_sha256"]) != expected_sources | {"productionMotionSubset"}:
        raise ValueError("Native preview source manifest is incomplete")
    for path in expected_sources:
        if sha((ROOT / path).read_bytes()) != manifest["source_sha256"][path]:
            raise ValueError("Stale native previews; rerender after changing " + path)
    motion = (ROOT / "testMugshot/Design/MugshotMotionSystem.swift").read_text()
    subset = b"import SwiftUI\n" + b"\n".join(source_block(motion, marker) for marker in [
        "enum MugshotMotion {", "enum MugshotDrinkAppearance:", "extension Comparable {",
    ])
    if sha(subset) != manifest["source_sha256"]["productionMotionSubset"]:
        raise ValueError("Native preview motion definitions changed; rerender")
    names = {pose["id"] + ".png" for pose in spec["poses"]}
    if set(manifest["renders"]) != names or {p.name for p in folder.glob("*.png")} != names:
        raise ValueError("Expected one native preview for every approved pose")
    for name, expected in manifest["renders"].items():
        if sha((folder / name).read_bytes()) != expected:
            raise ValueError("Native preview bytes changed: " + name)


def alpha_bounds(data: bytes) -> tuple[int, int, tuple[int, int, int, int]]:
    if not data.startswith(b"\x89PNG\r\n\x1a\n"):
        raise ValueError("Expected original generated PNG")
    width, height, depth, color = struct.unpack(">IIBB", data[16:26])
    if depth != 8 or color != 6 or data[28] != 0:
        raise ValueError("Mugsy needs a non-interlaced 8-bit RGBA PNG")
    compressed = []
    offset = 8
    while offset < len(data):
        size = struct.unpack(">I", data[offset:offset + 4])[0]
        if data[offset + 4:offset + 8] == b"IDAT":
            compressed.append(data[offset + 8:offset + 8 + size])
        offset += size + 12
    raw = zlib.decompress(b"".join(compressed))
    stride = width * 4 + 1
    if len(raw) != stride * height:
        raise ValueError("Unexpected PNG scanline length")
    previous = [0] * width
    low, high = 255, 0
    left, top, right, bottom = width, height, -1, -1
    for y in range(height):
        offset = y * stride
        kind = raw[offset]
        values = raw[offset + 4:offset + stride:4]
        current = []
        for x, value in enumerate(values):
            a = current[x - 1] if x else 0
            b = previous[x]
            c = previous[x - 1] if x else 0
            if kind == 1:
                value = (value + a) & 255
            elif kind == 2:
                value = (value + b) & 255
            elif kind == 3:
                value = (value + (a + b) // 2) & 255
            elif kind == 4:
                prediction = a + b - c
                distances = (abs(prediction - a), abs(prediction - b), abs(prediction - c))
                predictor = (a, b, c)[distances.index(min(distances))]
                value = (value + predictor) & 255
            elif kind != 0:
                raise ValueError("Unsupported PNG filter")
            current.append(value)
            low, high = min(low, value), max(high, value)
            if value > 16:
                left, top, right, bottom = min(left, x), min(top, y), max(right, x), max(bottom, y)
        previous = current
    if low != 0 or high != 255:
        raise ValueError("Expected genuine transparent and opaque pixels")
    if not (0 < left < right < width - 1 and 0 < top < bottom < height - 1):
        raise ValueError("Character or accessory touches/crops the canvas edge")
    return width, height, (left, top, right, bottom)


def verify(spec: dict) -> list[dict]:
    reference = (ROOT / spec["reference_path"]).read_bytes()
    if sha(reference) != spec["reference_sha256"]:
        raise ValueError("Immutable Mugsy identity master changed")
    if (ROOT / "docs/brand/identity/Mugsy-identity-master.png").read_bytes() != reference:
        raise ValueError("Brand identity master drifted from native master")
    model = (ROOT / "testMugshot/Views/Components/MugsyModelView.swift").read_text()
    for name, expected in spec["core_geometry_sha256"].items():
        if sha(source_block(model, "private struct " + name + ":")) != expected:
            raise ValueError("Core identity geometry changed: " + name)
    poses = spec["poses"]
    if len(poses) != 18 or len({p["id"] for p in poses}) != 18 or len({p["asset_name"] for p in poses}) != 18:
        raise ValueError("Expected 18 unique named pose/asset contracts")
    records = []
    for pose in poses:
        folder = ASSETS / (pose["asset_name"] + ".imageset")
        contents = json.loads((folder / "Contents.json").read_text())
        filename = next(image["filename"] for image in contents["images"] if image.get("filename"))
        path = folder / filename
        data = path.read_bytes()
        if sha(data) != pose.get("artwork_sha256"):
            raise ValueError("Artwork changed since optical review: " + pose["id"])
        width, height, bounds = alpha_bounds(data)
        if width != height:
            raise ValueError("Pose needs a square canvas: " + pose["id"])
        measured = [round(bounds[0] / width, 6), round(bounds[1] / height, 6), round((bounds[2] - bounds[0] + 1) / width, 6), round((bounds[3] - bounds[1] + 1) / height, 6)]
        if pose.get("artwork_bounds") != measured:
            raise ValueError("Artwork registration no longer matches alpha bounds: " + pose["id"])
        receipt = json.loads((ROOT / f"docs/brand/generation/mugsy-{pose['id']}.json").read_text())
        if receipt["reference_sha256"] != spec["reference_sha256"]:
            raise ValueError("Generation used the wrong identity: " + pose["id"])
        if receipt.get("output_sha256") != sha(data):
            raise ValueError("Generation receipt output hash mismatch: " + pose["id"])
        if pose.get("generation_status") != "identity-reviewed":
            raise ValueError("Optical identity review not recorded: " + pose["id"])
        records.append({"id": pose["id"], "asset": pose["asset_name"], "sha256": sha(data), "width": width, "height": height, "alpha_bounds": bounds})
    return records


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build", action="store_true", help="Regenerate the Swift catalog before artwork integration")
    parser.add_argument("--check", action="store_true", help="Check geometry, master, catalog, PNG alpha, margins and review records")
    args = parser.parse_args()
    try:
        spec = json.loads(SPEC.read_text())
        expected = render(spec)
        if args.build:
            SWIFT.write_text(expected)
            print("Generated 18 typed native Mugsy pose configurations.")
            return 0
        if SWIFT.read_text() != expected:
            raise ValueError("Native pose catalog drift; review the specification and rebuild")
        records = verify(spec)
        verify_native_previews(spec)
        print(f"Mugsy identity, seven core shapes, 18 native mappings, alpha, margins, review gates and native preview hashes passed ({len(records)} PNGs).")
        return 0
    except (OSError, ValueError, KeyError, StopIteration) as error:
        print("Mugsy catalog check failed: " + str(error), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
